CREATE TABLE IF NOT EXISTS applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  cv_url VARCHAR(255),
  cover_letter TEXT,
  status application_status NOT NULL DEFAULT 'pending',
  applied_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_application UNIQUE (job_id, candidate_id)
);

ALTER TABLE applications
  ADD COLUMN IF NOT EXISTS cv_url VARCHAR(255),
  ADD COLUMN IF NOT EXISTS cover_letter TEXT,
  ADD COLUMN IF NOT EXISTS status application_status NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS applied_at TIMESTAMPTZ DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS status_note TEXT,
  ADD COLUMN IF NOT EXISTS ai_score NUMERIC(5,2),
  ADD COLUMN IF NOT EXISTS ai_label VARCHAR(50),
  ADD COLUMN IF NOT EXISTS ai_analyzed_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS saved_jobs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
  job_id INTEGER NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  saved_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_save UNIQUE (candidate_id, job_id)
);

ALTER TABLE saved_jobs
  ADD COLUMN IF NOT EXISTS saved_at TIMESTAMPTZ DEFAULT NOW();

CREATE INDEX IF NOT EXISTS idx_applications_candidate_id
  ON applications(candidate_id);
CREATE INDEX IF NOT EXISTS idx_applications_job_id
  ON applications(job_id);
CREATE INDEX IF NOT EXISTS idx_saved_jobs_candidate_id
  ON saved_jobs(candidate_id);
